/** t('kk', 'found', { name }) — подстановка {переменных}; если ключа нет, берётся казахский. */
export function t(lang, key, vars = {}) {
  const tpl = DICT[normLang(lang)][key] ?? DICT[DEFAULT_LANG][key] ?? key;
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** Обращение к родителю в рассылке (на языке получателя). name уже экранирован, если нужно. */
export const greeting = (lang, name) => (name ? t(lang, 'greeting_name', { name }) : t(lang, 'greeting_plain'));

